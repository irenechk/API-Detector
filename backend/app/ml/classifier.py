"""
ML-powered API classifier.

Trains and serves multiple models for API endpoint classification:
  - API category (multi-class): auth, user_mgmt, data_crud, admin, etc.
  - Vulnerability types (multi-label): which vulnerabilities apply
  - Overall severity (multi-class): critical, high, medium, low
  - Risk score (regression): 0-100

Uses TF-IDF vectorization of endpoint paths + HTTP method features,
trained on data generated by the rule-based labeling system.
"""

import os
import re
import pickle
import logging
from pathlib import Path
from typing import Optional

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, RandomForestRegressor
from sklearn.multiclass import OneVsRestClassifier
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import LabelEncoder, MultiLabelBinarizer
from sklearn.model_selection import train_test_split

logger = logging.getLogger(__name__)

# ── Constants ───────────────────────────────────────────────────────────────

MODEL_DIR = Path(__file__).parent / "models"
MODEL_DIR.mkdir(exist_ok=True)

MODEL_FILES = {
    "category": MODEL_DIR / "category_classifier.pkl",
    "vulnerability": MODEL_DIR / "vulnerability_classifier.pkl",
    "severity": MODEL_DIR / "severity_classifier.pkl",
    "risk": MODEL_DIR / "risk_regressor.pkl",
    "vectorizer": MODEL_DIR / "tfidf_vectorizer.pkl",
    "label_encoders": MODEL_DIR / "label_encoders.pkl",
}

VULN_TYPES = [
    "Exposed Admin Interface",
    "Sensitive Data Exposure",
    "Insecure Direct Object Reference (IDOR)",
    "Authentication Bypass",
    "Mass Assignment / API Abuse",
    "Missing Rate Limiting",
    "GraphQL Introspection Enabled",
    "API Documentation Leakage",
    "File Operation Abuse",
    "CORS Misconfiguration",
    "Information Disclosure",
]

SEVERITY_LEVELS = ["low", "medium", "high", "critical"]

API_CATEGORIES = [
    "authentication", "user_management", "data_crud", "admin",
    "system_health", "file_operations", "configuration", "reporting",
    "notifications", "search", "messaging", "payment", "analytics",
    "integration", "unknown",
]


# ── Feature Engineering ─────────────────────────────────────────────────────

def _extract_path_features(path: str, method: str) -> str:
    """Create a rich text representation of an endpoint for TF-IDF."""
    path_lower = path.lower()

    # Tokenize path by common separators
    tokens = []
    for part in re.split(r"[/\-_.#?=&]", path_lower):
        part = part.strip()
        if part:
            tokens.append(part)

    # Add n-gram-like features
    path_segments = [s for s in path_lower.split("/") if s]
    for i in range(len(path_segments) - 1):
        tokens.append(f"seg_{path_segments[i]}_{path_segments[i+1]}")

    # Add structural indicators
    if re.search(r"/api/", path_lower):
        tokens.append("has_api_prefix")
    if re.search(r"/v\d+/", path_lower):
        tokens.append("has_versioned_path")
    if re.search(r"/\d{4,}", path_lower):
        tokens.append("has_numeric_id")
    if re.search(r"/[a-f0-9]{8}(-[a-f0-9]{4}){3}-[a-f0-9]{12}", path_lower):
        tokens.append("has_uuid")
    if method.upper() in ("POST", "PUT", "PATCH", "DELETE"):
        tokens.append(f"method_{method.upper()}")

    return " ".join(tokens)


def _prepare_features(paths: list[str], methods: list[str]) -> list[str]:
    """Convert raw endpoint data into feature vectors."""
    return [_extract_path_features(p, m) for p, m in zip(paths, methods)]


# ── Training ────────────────────────────────────────────────────────────────

class APIClassifier:
    """Multi-model ML classifier for API endpoints."""

    def __init__(self):
        self.vectorizer: Optional[TfidfVectorizer] = None
        self.category_model: Optional[Pipeline] = None
        self.vulnerability_model: Optional[OneVsRestClassifier] = None
        self.severity_model: Optional[Pipeline] = None
        self.risk_model: Optional[Pipeline] = None
        self.category_encoder: Optional[LabelEncoder] = None
        self.severity_encoder: Optional[LabelEncoder] = None
        self.mlb: Optional[MultiLabelBinarizer] = None
        self._fitted = False

    def _build_category_pipeline(self) -> Pipeline:
        return Pipeline([
            ("clf", LogisticRegression(max_iter=1000, C=10, random_state=42)),
        ])

    def _build_vulnerability_pipeline(self) -> OneVsRestClassifier:
        return OneVsRestClassifier(
            LogisticRegression(max_iter=1000, C=5, random_state=42),
        )

    def _build_severity_pipeline(self) -> Pipeline:
        return Pipeline([
            ("clf", LogisticRegression(max_iter=1000, C=10, random_state=42)),
        ])

    def _build_risk_pipeline(self) -> Pipeline:
        return Pipeline([
            ("clf", RandomForestRegressor(n_estimators=200, max_depth=10, random_state=42)),
        ])

    def fit(self, samples: list[dict]) -> "APIClassifier":
        """Train all models on labeled sample data."""
        paths = [s["endpoint_path"] for s in samples]
        methods = [s["http_method"] for s in samples]
        features = _prepare_features(paths, methods)

        # Vectorize
        self.vectorizer = TfidfVectorizer(
            max_features=1000,
            ngram_range=(1, 3),
            analyzer="word",
            sublinear_tf=True,
        )
        X = self.vectorizer.fit_transform(features)
        logger.info(f"Vectorized {len(samples)} samples -> {X.shape[1]} features")

        # ── Category classifier ──
        categories = [s["category"] for s in samples]
        self.category_encoder = LabelEncoder()
        y_category = self.category_encoder.fit_transform(categories)
        self.category_model = self._build_category_pipeline()
        self.category_model.fit(X, y_category)
        logger.info(f"Category model trained ({len(self.category_encoder.classes_)} classes)")

        # ── Vulnerability multi-label classifier ──
        vuln_lists = [s["vulnerabilities"] for s in samples]
        self.mlb = MultiLabelBinarizer(classes=VULN_TYPES)
        y_vuln = self.mlb.fit_transform(vuln_lists)
        self.vulnerability_model = self._build_vulnerability_pipeline()
        self.vulnerability_model.fit(X, y_vuln)
        logger.info(f"Vulnerability model trained ({len(VULN_TYPES)} labels)")

        # ── Severity classifier ──
        severities = [s["severity"] for s in samples]
        self.severity_encoder = LabelEncoder()
        y_severity = self.severity_encoder.fit_transform(severities)
        self.severity_model = self._build_severity_pipeline()
        self.severity_model.fit(X, y_severity)
        logger.info(f"Severity model trained ({len(self.severity_encoder.classes_)} classes)")

        # ── Risk score regressor ──
        risk_scores = [s["risk_score"] for s in samples]
        self.risk_model = self._build_risk_pipeline()
        self.risk_model.fit(X, risk_scores)
        logger.info("Risk regressor trained")

        self._fitted = True
        return self

    def predict(self, path: str, method: str = "GET") -> dict:
        """Run all models on a single endpoint and return predictions."""
        if not self._fitted:
            # Fall back to rule-based if models aren't loaded
            return self._rule_based_fallback(path, method)

        feature = _prepare_features([path], [method])
        X = self.vectorizer.transform(feature)

        # Category
        cat_idx = self.category_model.predict(X)[0]
        category = self.category_encoder.inverse_transform([cat_idx])[0]

        # Vulnerabilities (multi-label)
        vuln_preds = self.vulnerability_model.predict(X)
        vulnerabilities = []
        for i, present in enumerate(vuln_preds[0]):
            if present:
                vulnerabilities.append(self.mlb.classes_[i])

        # Severity
        sev_idx = self.severity_model.predict(X)[0]
        severity = self.severity_encoder.inverse_transform([sev_idx])[0]

        # Risk score
        risk_score_raw = self.risk_model.predict(X)[0]
        risk_score = max(0, min(100, int(round(risk_score_raw))))

        # Confidence scores
        cat_probas = self.category_model.predict_proba(X)[0]
        cat_confidence = float(max(cat_probas))

        sev_probas = self.severity_model.predict_proba(X)[0]
        sev_confidence = float(max(sev_probas))

        vuln_probas = self.vulnerability_model.predict_proba(X)[0]
        vuln_confidences = {}
        for i in range(len(self.mlb.classes_)):
            if vuln_preds[0][i]:
                vuln_confidences[self.mlb.classes_[i]] = float(vuln_probas[i])

        return {
            "category": category,
            "category_confidence": round(cat_confidence, 3),
            "vulnerabilities": vulnerabilities,
            "vulnerability_confidences": {v: round(vuln_confidences.get(v, 0), 3) for v in vulnerabilities},
            "severity": severity,
            "severity_confidence": round(sev_confidence, 3),
            "risk_score": risk_score,
            "ml_model_version": "1.0",
        }

    def _rule_based_fallback(self, path: str, method: str = "GET") -> dict:
        """Fallback to keyword-based classification when ML model is unavailable."""
        from app.ml.data import classify_vulnerabilities, classify_severity, classify_api_category, estimate_risk_score
        vulns = classify_vulnerabilities(path, method)
        return {
            "category": classify_api_category(path, method),
            "category_confidence": 1.0,
            "vulnerabilities": vulns,
            "vulnerability_confidences": {v: 1.0 for v in vulns},
            "severity": classify_severity(vulns),
            "severity_confidence": 1.0,
            "risk_score": estimate_risk_score(path, method, vulns, classify_severity(vulns)),
            "ml_model_version": "rule-based-fallback",
        }

    def save(self, directory: Optional[Path] = None) -> None:
        """Save all trained models to disk."""
        save_dir = directory or MODEL_DIR
        save_dir.mkdir(parents=True, exist_ok=True)

        with open(save_dir / "category_classifier.pkl", "wb") as f:
            pickle.dump(self.category_model, f)
        with open(save_dir / "vulnerability_classifier.pkl", "wb") as f:
            pickle.dump(self.vulnerability_model, f)
        with open(save_dir / "severity_classifier.pkl", "wb") as f:
            pickle.dump(self.severity_model, f)
        with open(save_dir / "risk_regressor.pkl", "wb") as f:
            pickle.dump(self.risk_model, f)
        with open(save_dir / "tfidf_vectorizer.pkl", "wb") as f:
            pickle.dump(self.vectorizer, f)

        label_encoders = {
            "category": self.category_encoder,
            "severity": self.severity_encoder,
            "mlb": self.mlb,
        }
        with open(save_dir / "label_encoders.pkl", "wb") as f:
            pickle.dump(label_encoders, f)

        logger.info(f"Models saved to {save_dir}")

    @classmethod
    def load(cls, directory: Optional[Path] = None) -> "APIClassifier":
        """Load trained models from disk."""
        load_dir = directory or MODEL_DIR
        required = list(MODEL_FILES.values())

        if not all(f.exists() for f in required):
            logger.warning("Model files not found at %s, using rule-based fallback", load_dir)
            instance = cls()
            instance._fitted = False
            return instance

        instance = cls()

        with open(load_dir / "category_classifier.pkl", "rb") as f:
            instance.category_model = pickle.load(f)
        with open(load_dir / "vulnerability_classifier.pkl", "rb") as f:
            instance.vulnerability_model = pickle.load(f)
        with open(load_dir / "severity_classifier.pkl", "rb") as f:
            instance.severity_model = pickle.load(f)
        with open(load_dir / "risk_regressor.pkl", "rb") as f:
            instance.risk_model = pickle.load(f)
        with open(load_dir / "tfidf_vectorizer.pkl", "rb") as f:
            instance.vectorizer = pickle.load(f)
        with open(load_dir / "label_encoders.pkl", "rb") as f:
            encoders = pickle.load(f)
            instance.category_encoder = encoders["category"]
            instance.severity_encoder = encoders["severity"]
            instance.mlb = encoders["mlb"]

        instance._fitted = True
        logger.info(f"Models loaded from {load_dir}")
        return instance


# ── Singleton for app-wide use ─────────────────────────────────────────────

_classifier_instance: Optional[APIClassifier] = None


def get_classifier() -> APIClassifier:
    """Get or create the classifier singleton."""
    global _classifier_instance
    if _classifier_instance is None:
        _classifier_instance = APIClassifier.load()
    return _classifier_instance


def classify_endpoint(path: str, method: str = "GET") -> dict:
    """Convenience function to classify a single API endpoint."""
    return get_classifier().predict(path, method)
